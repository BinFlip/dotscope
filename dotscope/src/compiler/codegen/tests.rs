#[test]
fn test_loop_variable_phi_nodes() {
    // Simple counting loop: i = 0; while (i < n) { i = i + 1; } return i;
    // This tests that loop variable phi nodes are properly handled.
    //
    // SSA Structure:
    //   Block 0 (entry):
    //     i_init = const 0
    //     goto Block 1
    //
    //   Block 1 (loop header):
    //     i_phi = phi(i_init from B0, i_next from B2)
    //     cond = clt(i_phi, n)
    //     branch cond -> B2 (body), B3 (exit)
    //
    //   Block 2 (loop body):
    //     one = const 1
    //     i_next = add(i_phi, one)
    //     goto Block 1
    //
    //   Block 3 (exit):
    //     return i_phi

    let mut ssa = SsaFunction::new(1, 1); // 1 arg (n), 1 local (i)

    // Variables
    let n_id = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::phi(0),
        SsaType::Unknown,
    );
    let i_init_id = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::instruction(0, 0),
        SsaType::Unknown,
    );
    let i_phi_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let cond_id = ssa.create_variable(
        VariableOrigin::Local(2),
        0,
        DefSite::instruction(1, 0),
        SsaType::Unknown,
    );
    let one_id = ssa.create_variable(
        VariableOrigin::Local(3),
        0,
        DefSite::instruction(2, 0),
        SsaType::Unknown,
    );
    let i_next_id = ssa.create_variable(
        VariableOrigin::Local(4),
        0,
        DefSite::instruction(2, 1),
        SsaType::Unknown,
    );

    // Block 0: entry - initialize i to 0
    let mut block0 = SsaBlock::new(0);
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: i_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block0);

    // Block 1: loop header with phi
    let mut block1 = SsaBlock::new(1);
    let mut phi = PhiNode::new(i_phi_id, VariableOrigin::Local(0));
    phi.add_operand(PhiOperand::new(i_init_id, 0));
    phi.add_operand(PhiOperand::new(i_next_id, 2));
    block1.add_phi(phi);
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Clt {
        dest: cond_id,
        left: i_phi_id,
        right: n_id,
        unsigned: false,
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: cond_id,
        true_target: 2,
        false_target: 3,
    }));
    ssa.add_block(block1);

    // Block 2: loop body - i = i + 1
    let mut block2 = SsaBlock::new(2);
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: one_id,
        value: ConstValue::I32(1),
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: i_next_id,
        left: i_phi_id,
        right: one_id,
        flags: None,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block2);

    // Block 3: exit - return i
    let mut block3 = SsaBlock::new(3);
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Return {
        value: Some(i_phi_id),
    }));
    ssa.add_block(block3);

    // Generate and check that it includes:
    // 1. ldloc for i_phi in both the loop body (for i + 1) and at return
    // 2. stloc for storing the incremented value back
    let mut gen = SsaCodeGenerator::new();
    let result = gen.generate(&ssa);
    assert!(result.is_ok(), "Codegen failed: {:?}", result.err());

    let (bytecode, _, num_locals) = result.unwrap();
    assert!(
        num_locals >= 1,
        "Should have at least 1 local for loop variable"
    );

    let instructions = decode_stream(&mut Parser::new(&bytecode), 0x1000).expect("decode failed");
    let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

    // The generated code must load the loop variable (ldloc) for both:
    // - The comparison (clt)
    // - The addition (i + 1)
    // - The return value
    let ldloc_count = mnemonics.iter().filter(|m| m.starts_with("ldloc")).count();
    assert!(
        ldloc_count >= 2,
        "Expected at least 2 ldloc for loop variable, got {}. Mnemonics: {:?}",
        ldloc_count,
        mnemonics
    );

    // Must have stloc for storing i_init and i_next
    let stloc_count = mnemonics.iter().filter(|m| m.starts_with("stloc")).count();
    assert!(
        stloc_count >= 1,
        "Expected at least 1 stloc for loop variable, got {}. Mnemonics: {:?}",
        stloc_count,
        mnemonics
    );

    // Must have ret somewhere (block layout may vary)
    assert!(
        mnemonics.contains(&"ret"),
        "Should have ret instruction. Mnemonics: {:?}",
        mnemonics
    );

    // Verify the ret loads from a local (the loop variable), not a constant
    // Find the instruction before ret
    let ret_idx = mnemonics.iter().position(|m| *m == "ret").unwrap();
    assert!(
        ret_idx > 0,
        "ret should not be the first instruction. Mnemonics: {:?}",
        mnemonics
    );
    let before_ret = mnemonics[ret_idx - 1];
    assert!(
        before_ret.starts_with("ldloc"),
        "Should load loop variable before ret, got '{}'. Mnemonics: {:?}",
        before_ret,
        mnemonics
    );

    println!("Loop codegen test passed. Generated: {:?}", mnemonics);
}

#[test]
fn test_fibonacci_style_loop() {
    // Fibonacci-style loop with multiple phi variables:
    // a = 0, b = 1, i = 2
    // while (i <= n) { temp = a + b; a = b; b = temp; i = i + 1; }
    // return b
    //
    // This tests multiple phi nodes in the same loop header.

    let mut ssa = SsaFunction::new(1, 4); // 1 arg (n), 4 locals (a, b, i, temp)

    // Variables - arguments
    let n_id = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::phi(0),
        SsaType::Unknown,
    );

    // Entry block variables
    let a_init_id = ssa.create_variable(
        VariableOrigin::Local(4),
        0,
        DefSite::instruction(0, 0),
        SsaType::Unknown,
    );
    let b_init_id = ssa.create_variable(
        VariableOrigin::Local(5),
        0,
        DefSite::instruction(0, 1),
        SsaType::Unknown,
    );
    let i_init_id = ssa.create_variable(
        VariableOrigin::Local(6),
        0,
        DefSite::instruction(0, 2),
        SsaType::Unknown,
    );

    // Phi variables at loop header
    let a_phi_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let b_phi_id = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let i_phi_id = ssa.create_variable(
        VariableOrigin::Local(2),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );

    // Loop header condition
    let cond_id = ssa.create_variable(
        VariableOrigin::Local(7),
        0,
        DefSite::instruction(1, 0),
        SsaType::Unknown,
    );

    // Loop body variables
    let temp_id = ssa.create_variable(
        VariableOrigin::Local(3),
        0,
        DefSite::instruction(2, 0),
        SsaType::Unknown,
    );
    let one_id = ssa.create_variable(
        VariableOrigin::Local(8),
        0,
        DefSite::instruction(2, 1),
        SsaType::Unknown,
    );
    let i_next_id = ssa.create_variable(
        VariableOrigin::Local(9),
        0,
        DefSite::instruction(2, 2),
        SsaType::Unknown,
    );

    // Block 0: entry - initialize a=0, b=1, i=2
    let mut block0 = SsaBlock::new(0);
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: a_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: b_init_id,
        value: ConstValue::I32(1),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: i_init_id,
        value: ConstValue::I32(2),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block0);

    // Block 1: loop header with phi nodes for a, b, i
    let mut block1 = SsaBlock::new(1);

    let mut phi_a = PhiNode::new(a_phi_id, VariableOrigin::Local(0));
    phi_a.add_operand(PhiOperand::new(a_init_id, 0));
    phi_a.add_operand(PhiOperand::new(b_phi_id, 2)); // a_next = b (old)
    block1.add_phi(phi_a);

    let mut phi_b = PhiNode::new(b_phi_id, VariableOrigin::Local(1));
    phi_b.add_operand(PhiOperand::new(b_init_id, 0));
    phi_b.add_operand(PhiOperand::new(temp_id, 2)); // b_next = temp
    block1.add_phi(phi_b);

    let mut phi_i = PhiNode::new(i_phi_id, VariableOrigin::Local(2));
    phi_i.add_operand(PhiOperand::new(i_init_id, 0));
    phi_i.add_operand(PhiOperand::new(i_next_id, 2));
    block1.add_phi(phi_i);

    // i <= n  means !(i > n) means cgt then branch on false
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Cgt {
        dest: cond_id,
        left: i_phi_id,
        right: n_id,
        unsigned: false,
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: cond_id,
        true_target: 3,  // exit if i > n
        false_target: 2, // continue if i <= n
    }));
    ssa.add_block(block1);

    // Block 2: loop body
    let mut block2 = SsaBlock::new(2);
    // temp = a + b
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: temp_id,
        left: a_phi_id,
        right: b_phi_id,
        flags: None,
    }));
    // i_next = i + 1
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: one_id,
        value: ConstValue::I32(1),
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: i_next_id,
        left: i_phi_id,
        right: one_id,
        flags: None,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block2);

    // Block 3: exit - return b
    let mut block3 = SsaBlock::new(3);
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Return {
        value: Some(b_phi_id),
    }));
    ssa.add_block(block3);

    // Generate code
    let mut gen = SsaCodeGenerator::new();
    let result = gen.generate(&ssa);
    assert!(result.is_ok(), "Codegen failed: {:?}", result.err());

    let (bytecode, _, num_locals) = result.unwrap();
    println!(
        "Fibonacci-style loop: {} bytes, {} locals",
        bytecode.len(),
        num_locals
    );

    let instructions = decode_stream(&mut Parser::new(&bytecode), 0x1000).expect("decode failed");
    let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();
    println!("Generated: {:?}", mnemonics);

    // Must have at least 3 locals for a, b, i
    assert!(
        num_locals >= 3,
        "Should have at least 3 locals for loop variables, got {}",
        num_locals
    );

    // Must have ret with ldloc before it (returning b)
    assert!(mnemonics.contains(&"ret"), "Should have ret");
    let ret_idx = mnemonics.iter().position(|m| *m == "ret").unwrap();
    let before_ret = mnemonics[ret_idx - 1];
    assert!(
        before_ret.starts_with("ldloc"),
        "Should load b before ret, got '{}'. Mnemonics: {:?}",
        before_ret,
        mnemonics
    );

    // Must have add instructions for temp=a+b and i=i+1
    let add_count = mnemonics.iter().filter(|m| **m == "add").count();
    assert!(
        add_count >= 2,
        "Should have at least 2 add instructions, got {}. Mnemonics: {:?}",
        add_count,
        mnemonics
    );

    // Must load a and b for the addition (ldloc for both phi variables)
    let ldloc_count = mnemonics.iter().filter(|m| m.starts_with("ldloc")).count();
    assert!(
        ldloc_count >= 4,
        "Should have at least 4 ldloc (a, b for add, i for cmp, b for ret), got {}. Mnemonics: {:?}",
        ldloc_count,
        mnemonics
    );
}

/// Verifies that Fibonacci method from TestApp.exe produces correct code after deobfuscation.
/// This is a regression test for the copy propagation bug that incorrectly merged loop variables.
#[test]
fn test_fibonacci_deobfuscation_preserves_semantics() {
    let path = fixture("packers/confuserex/1.6.0/original.exe");
    let assembly = CilObject::from_path_with_validation(&path, ValidationConfig::analysis())
        .expect("the fixture loads");

    // Run full deobfuscation
    let config = EngineConfig::default();
    let engine = DeobfuscationEngine::new(config);
    let (output, _) = engine.process_assembly(assembly).expect("deobfuscation");

    // Find Fibonacci method
    let tables = output.tables().expect("tables");
    let method_table = tables.table::<MethodDefRaw>().expect("method table");
    let strings = output.strings().expect("strings");

    let mut found = false;
    for row in method_table.iter() {
        let row = row.expect("row parses");
        let name = strings.get(row.name as usize).unwrap_or("");
        if name != "Fibonacci" {
            continue;
        }
        found = true;

        let rva = row.rva as usize;
        if rva == 0 {
            continue;
        }

        let file = output.file();
        let offset = file.rva_to_offset(rva).expect("rva to offset");
        let data = &file.data()[offset..];
        let body = MethodBody::from(data).expect("method body");
        let bytecode = &data[body.size_header..body.size_header + body.size_code];

        let instructions = decode_stream(&mut Parser::new(bytecode), 0).expect("decode");
        let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

        // The main return should load from a local variable, not a constant
        // (The bug caused it to return constant 1 instead of the computed value)
        let ret_positions: Vec<usize> = mnemonics
            .iter()
            .enumerate()
            .filter(|(_, m)| **m == "ret")
            .map(|(i, _)| i)
            .collect();

        if let Some(&last_ret) = ret_positions.last() {
            if last_ret > 0 {
                let before_ret = mnemonics[last_ret - 1];
                assert!(
                    !before_ret.starts_with("ldc.i4"),
                    "BUG: Fibonacci returns a constant instead of computed value. \
                     The final return is preceded by '{}' instead of ldloc",
                    before_ret
                );
            }
        }

        // Verify the add instruction in loop body uses TWO DIFFERENT locals (a + b, not a + a)
        // Find sequences: ldloc.X, ldloc.Y, add where X != Y
        for (i, mnemonic) in mnemonics.iter().enumerate() {
            if *mnemonic == "add" && i >= 2 {
                let prev1 = mnemonics[i - 1];
                let prev2 = mnemonics[i - 2];
                if prev1.starts_with("ldloc") && prev2.starts_with("ldloc") {
                    // In Fibonacci, the add for temp=a+b should use different locals
                    // A "dup, add" pattern would indicate the bug
                    assert_ne!(
                        prev1, prev2,
                        "BUG: add uses same local twice ({}, {}). Should be a + b, not a + a",
                        prev2, prev1
                    );
                }
            }
        }
    }

    assert!(found, "Fibonacci method not found");
}

/// Verifies that all pass combinations produce valid code for Fibonacci.
/// This catches regressions where specific pass orderings break loop semantics.
#[test]
fn test_fibonacci_pass_combinations() {
    let path = fixture("packers/confuserex/1.6.0/original.exe");

    // Test key pass combinations
    let configs: Vec<(&str, EngineConfig)> = vec![
        (
            "copy_prop_only",
            EngineConfig {
                passes: PassConfig {
                    dead_code_elimination: false,
                    copy_propagation: true,
                    constant_propagation: false,
                    strength_reduction: false,
                    control_flow_simplification: false,
                    opaque_predicate_removal: false,
                    ..Default::default()
                },
                ..EngineConfig::default()
            },
        ),
        (
            "dce_copy_prop",
            EngineConfig {
                passes: PassConfig {
                    dead_code_elimination: true,
                    copy_propagation: true,
                    constant_propagation: false,
                    strength_reduction: false,
                    control_flow_simplification: false,
                    opaque_predicate_removal: false,
                    ..Default::default()
                },
                ..EngineConfig::default()
            },
        ),
        ("full_pipeline", EngineConfig::default()),
    ];

    for (name, config) in configs {
        let assembly = CilObject::from_path_with_validation(&path, ValidationConfig::analysis())
            .expect("the fixture loads");

        let engine = DeobfuscationEngine::new(config);
        let (output, _) = engine.process_assembly(assembly).expect("deobfuscate");

        let tables = output.tables().expect("tables");
        let method_table = tables.table::<MethodDefRaw>().expect("method table");
        let strings = output.strings().expect("strings");

        for row in method_table.iter() {
            let row = row.expect("row parses");
            let method_name = strings.get(row.name as usize).unwrap_or("");
            if method_name != "Fibonacci" {
                continue;
            }

            let rva = row.rva as usize;
            if rva == 0 {
                continue;
            }

            let file = output.file();
            let offset = file.rva_to_offset(rva).expect("rva to offset");
            let data = &file.data()[offset..];
            let body = MethodBody::from(data).expect("method body");
            let bytecode = &data[body.size_header..body.size_header + body.size_code];

            let instructions = decode_stream(&mut Parser::new(bytecode), 0).expect("decode");
            let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

            // Find last ret and check it doesn't return a constant
            let ret_positions: Vec<usize> = mnemonics
                .iter()
                .enumerate()
                .filter(|(_, m)| **m == "ret")
                .map(|(i, _)| i)
                .collect();

            if let Some(&last_ret) = ret_positions.last() {
                if last_ret > 0 {
                    let before_ret = mnemonics[last_ret - 1];
                    assert!(
                        !before_ret.starts_with("ldc.i4"),
                        "Config '{}': Fibonacci returns constant instead of computed value",
                        name
                    );
                }
            }
        }
    }
}

/// Test factorial-style loop: result *= i
#[test]
fn test_factorial_style_loop() {
    // Factorial: result = 1; for (i = n; i > 1; i--) result *= i; return result;

    let mut ssa = SsaFunction::new(1, 2); // 1 arg (n), 2 locals (result, i)

    // Variables
    // An argument has its signature's type, as a lift gives it.
    let n_id = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::phi(0),
        SsaType::I32,
    );
    let result_init_id = ssa.create_variable(
        VariableOrigin::Local(2),
        0,
        DefSite::instruction(0, 0),
        SsaType::Unknown,
    );
    let result_phi_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let i_phi_id = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let one_id = ssa.create_variable(
        VariableOrigin::Local(3),
        0,
        DefSite::instruction(1, 0),
        SsaType::Unknown,
    );
    let cond_id = ssa.create_variable(
        VariableOrigin::Local(4),
        0,
        DefSite::instruction(1, 1),
        SsaType::Unknown,
    );
    let result_next_id = ssa.create_variable(
        VariableOrigin::Local(5),
        0,
        DefSite::instruction(2, 0),
        SsaType::Unknown,
    );
    let i_next_id = ssa.create_variable(
        VariableOrigin::Local(6),
        0,
        DefSite::instruction(2, 1),
        SsaType::Unknown,
    );

    // Block 0: entry - result = 1
    let mut block0 = SsaBlock::new(0);
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: result_init_id,
        value: ConstValue::I32(1),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block0);

    // Block 1: loop header
    let mut block1 = SsaBlock::new(1);

    let mut phi_result = PhiNode::new(result_phi_id, VariableOrigin::Local(0));
    phi_result.add_operand(PhiOperand::new(result_init_id, 0));
    phi_result.add_operand(PhiOperand::new(result_next_id, 2));
    block1.add_phi(phi_result);

    let mut phi_i = PhiNode::new(i_phi_id, VariableOrigin::Local(1));
    phi_i.add_operand(PhiOperand::new(n_id, 0));
    phi_i.add_operand(PhiOperand::new(i_next_id, 2));
    block1.add_phi(phi_i);

    // i > 1 ?
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: one_id,
        value: ConstValue::I32(1),
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Cgt {
        dest: cond_id,
        left: i_phi_id,
        right: one_id,
        unsigned: false,
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: cond_id,
        true_target: 2,
        false_target: 3,
    }));
    ssa.add_block(block1);

    // Block 2: loop body - result *= i; i--
    let mut block2 = SsaBlock::new(2);
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Mul {
        dest: result_next_id,
        left: result_phi_id,
        right: i_phi_id,
        flags: None,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Sub {
        dest: i_next_id,
        left: i_phi_id,
        right: one_id,
        flags: None,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block2);

    // Block 3: exit
    let mut block3 = SsaBlock::new(3);
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Return {
        value: Some(result_phi_id),
    }));
    ssa.add_block(block3);

    // Generate and verify
    let mut gen = SsaCodeGenerator::new();
    let result = gen.generate(&ssa);
    assert!(result.is_ok(), "Codegen failed: {:?}", result.err());

    let (bytecode, _, num_locals) = result.unwrap();
    let instructions = decode_stream(&mut Parser::new(&bytecode), 0x1000).expect("decode");
    let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

    // Must have mul for result *= i
    assert!(mnemonics.contains(&"mul"), "Should have mul instruction");

    // Must have sub for i--
    assert!(mnemonics.contains(&"sub"), "Should have sub instruction");

    // Must return from local, not constant
    let ret_idx = mnemonics.iter().position(|m| *m == "ret").unwrap();
    assert!(
        mnemonics[ret_idx - 1].starts_with("ldloc"),
        "Should load result before ret"
    );

    // `i` may live in the argument it starts as, so one local suffices.
    assert!(num_locals >= 1, "Should have a local for result");
    assert_eq!(
        run_integer_cil(&bytecode, &[StackValue::I4(5)]),
        StackValue::I4(120),
        "5! is 120"
    );
}

/// Test nested loop pattern: common in matrix operations
#[test]
fn test_nested_loop_pattern() {
    // Outer loop: i from 0 to n
    // Inner loop: j from 0 to m
    // sum += arr[i][j] (simplified to just sum += 1)

    let mut ssa = SsaFunction::new(2, 3); // 2 args (n, m), 3 locals (sum, i, j)

    // Variables
    let n_id = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::phi(0),
        SsaType::Unknown,
    );
    let m_id = ssa.create_variable(
        VariableOrigin::Argument(1),
        0,
        DefSite::phi(0),
        SsaType::Unknown,
    );

    // Entry block inits
    let sum_init_id = ssa.create_variable(
        VariableOrigin::Local(3),
        0,
        DefSite::instruction(0, 0),
        SsaType::Unknown,
    );
    let i_init_id = ssa.create_variable(
        VariableOrigin::Local(4),
        0,
        DefSite::instruction(0, 1),
        SsaType::Unknown,
    );

    // Outer loop header phis
    let sum_outer_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let i_phi_id = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );

    // Outer loop condition
    let outer_cond_id = ssa.create_variable(
        VariableOrigin::Local(5),
        0,
        DefSite::instruction(1, 0),
        SsaType::Unknown,
    );

    // Inner loop setup
    let j_init_id = ssa.create_variable(
        VariableOrigin::Local(6),
        0,
        DefSite::instruction(2, 0),
        SsaType::Unknown,
    );

    // Inner loop header phis
    let sum_inner_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(3),
        SsaType::Unknown,
    );
    let j_phi_id = ssa.create_variable(
        VariableOrigin::Local(2),
        0,
        DefSite::phi(3),
        SsaType::Unknown,
    );

    // Inner loop condition
    let inner_cond_id = ssa.create_variable(
        VariableOrigin::Local(7),
        0,
        DefSite::instruction(3, 0),
        SsaType::Unknown,
    );

    // Inner body updates
    let one_id = ssa.create_variable(
        VariableOrigin::Local(8),
        0,
        DefSite::instruction(4, 0),
        SsaType::Unknown,
    );
    let sum_next_id = ssa.create_variable(
        VariableOrigin::Local(9),
        0,
        DefSite::instruction(4, 1),
        SsaType::Unknown,
    );
    let j_next_id = ssa.create_variable(
        VariableOrigin::Local(10),
        0,
        DefSite::instruction(4, 2),
        SsaType::Unknown,
    );

    // Inner loop exit -> outer loop continue
    let outer_one_id = ssa.create_variable(
        VariableOrigin::Local(12),
        0,
        DefSite::instruction(5, 0),
        SsaType::Unknown,
    );
    let i_next_id = ssa.create_variable(
        VariableOrigin::Local(11),
        0,
        DefSite::instruction(5, 1),
        SsaType::Unknown,
    );

    // Block 0: entry
    let mut block0 = SsaBlock::new(0);
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: sum_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: i_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block0);

    // Block 1: outer loop header
    let mut block1 = SsaBlock::new(1);
    let mut phi_sum_outer = PhiNode::new(sum_outer_id, VariableOrigin::Local(0));
    phi_sum_outer.add_operand(PhiOperand::new(sum_init_id, 0));
    phi_sum_outer.add_operand(PhiOperand::new(sum_inner_id, 5));
    block1.add_phi(phi_sum_outer);

    let mut phi_i = PhiNode::new(i_phi_id, VariableOrigin::Local(1));
    phi_i.add_operand(PhiOperand::new(i_init_id, 0));
    phi_i.add_operand(PhiOperand::new(i_next_id, 5));
    block1.add_phi(phi_i);

    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Clt {
        dest: outer_cond_id,
        left: i_phi_id,
        right: n_id,
        unsigned: false,
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: outer_cond_id,
        true_target: 2,
        false_target: 6,
    }));
    ssa.add_block(block1);

    // Block 2: outer body start - init j
    let mut block2 = SsaBlock::new(2);
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: j_init_id,
        value: ConstValue::I32(0),
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 3 }));
    ssa.add_block(block2);

    // Block 3: inner loop header
    let mut block3 = SsaBlock::new(3);
    let mut phi_sum_inner = PhiNode::new(sum_inner_id, VariableOrigin::Local(0));
    phi_sum_inner.add_operand(PhiOperand::new(sum_outer_id, 2));
    phi_sum_inner.add_operand(PhiOperand::new(sum_next_id, 4));
    block3.add_phi(phi_sum_inner);

    let mut phi_j = PhiNode::new(j_phi_id, VariableOrigin::Local(2));
    phi_j.add_operand(PhiOperand::new(j_init_id, 2));
    phi_j.add_operand(PhiOperand::new(j_next_id, 4));
    block3.add_phi(phi_j);

    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Clt {
        dest: inner_cond_id,
        left: j_phi_id,
        right: m_id,
        unsigned: false,
    }));
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: inner_cond_id,
        true_target: 4,
        false_target: 5,
    }));
    ssa.add_block(block3);

    // Block 4: inner body
    let mut block4 = SsaBlock::new(4);
    block4.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: one_id,
        value: ConstValue::I32(1),
    }));
    block4.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: sum_next_id,
        left: sum_inner_id,
        right: one_id,
        flags: None,
    }));
    block4.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: j_next_id,
        left: j_phi_id,
        right: one_id,
        flags: None,
    }));
    block4.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 3 }));
    ssa.add_block(block4);

    // Block 5: inner exit -> increment i
    let mut block5 = SsaBlock::new(5);
    block5.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: outer_one_id,
        value: ConstValue::I32(1),
    }));
    block5.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: i_next_id,
        left: i_phi_id,
        right: outer_one_id,
        flags: None,
    }));
    block5.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block5);

    // Block 6: exit
    let mut block6 = SsaBlock::new(6);
    block6.add_instruction(SsaInstruction::synthetic(SsaOp::Return {
        value: Some(sum_outer_id),
    }));
    ssa.add_block(block6);

    // Generate and verify
    let mut gen = SsaCodeGenerator::new();
    let result = gen.generate(&ssa);
    assert!(result.is_ok(), "Codegen failed: {:?}", result.err());

    let (bytecode, _, num_locals) = result.unwrap();
    let instructions = decode_stream(&mut Parser::new(&bytecode), 0x1000).expect("decode");
    let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

    // Should have multiple comparison and branch instructions (nested loops)
    let clt_count = mnemonics.iter().filter(|m| **m == "clt").count();
    assert!(
        clt_count >= 2,
        "Should have at least 2 comparisons for nested loops"
    );

    // Should have multiple add instructions
    let add_count = mnemonics.iter().filter(|m| **m == "add").count();
    assert!(add_count >= 3, "Should have adds for sum++, j++, i++");

    assert!(
        num_locals >= 3,
        "Should have at least 3 locals, got {}",
        num_locals
    );
}

/// Test accumulator pattern with early exit (break condition)
#[test]
fn test_accumulator_with_early_exit() {
    // sum = 0; for (i = 0; i < n; i++) { sum += i; if (sum > 100) break; } return sum;

    let mut ssa = SsaFunction::new(1, 2); // 1 arg (n), 2 locals (sum, i)

    // Variables
    let n_id = ssa.create_variable(
        VariableOrigin::Argument(0),
        0,
        DefSite::phi(0),
        SsaType::Unknown,
    );
    let sum_init_id = ssa.create_variable(
        VariableOrigin::Local(2),
        0,
        DefSite::instruction(0, 0),
        SsaType::Unknown,
    );
    let i_init_id = ssa.create_variable(
        VariableOrigin::Local(3),
        0,
        DefSite::instruction(0, 1),
        SsaType::Unknown,
    );
    let sum_phi_id = ssa.create_variable(
        VariableOrigin::Local(0),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let i_phi_id = ssa.create_variable(
        VariableOrigin::Local(1),
        0,
        DefSite::phi(1),
        SsaType::Unknown,
    );
    let loop_cond_id = ssa.create_variable(
        VariableOrigin::Local(4),
        0,
        DefSite::instruction(1, 0),
        SsaType::Unknown,
    );
    let sum_next_id = ssa.create_variable(
        VariableOrigin::Local(5),
        0,
        DefSite::instruction(2, 0),
        SsaType::Unknown,
    );
    let hundred_id = ssa.create_variable(
        VariableOrigin::Local(6),
        0,
        DefSite::instruction(2, 1),
        SsaType::Unknown,
    );
    let break_cond_id = ssa.create_variable(
        VariableOrigin::Local(7),
        0,
        DefSite::instruction(2, 2),
        SsaType::Unknown,
    );
    let one_id = ssa.create_variable(
        VariableOrigin::Local(8),
        0,
        DefSite::instruction(3, 0),
        SsaType::Unknown,
    );
    let i_next_id = ssa.create_variable(
        VariableOrigin::Local(9),
        0,
        DefSite::instruction(3, 1),
        SsaType::Unknown,
    );

    // Block 0: entry
    let mut block0 = SsaBlock::new(0);
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: sum_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: i_init_id,
        value: ConstValue::I32(0),
    }));
    block0.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block0);

    // Block 1: loop header
    let mut block1 = SsaBlock::new(1);

    let mut phi_sum = PhiNode::new(sum_phi_id, VariableOrigin::Local(0));
    phi_sum.add_operand(PhiOperand::new(sum_init_id, 0));
    phi_sum.add_operand(PhiOperand::new(sum_next_id, 3));
    block1.add_phi(phi_sum);

    let mut phi_i = PhiNode::new(i_phi_id, VariableOrigin::Local(1));
    phi_i.add_operand(PhiOperand::new(i_init_id, 0));
    phi_i.add_operand(PhiOperand::new(i_next_id, 3));
    block1.add_phi(phi_i);

    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Clt {
        dest: loop_cond_id,
        left: i_phi_id,
        right: n_id,
        unsigned: false,
    }));
    block1.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: loop_cond_id,
        true_target: 2,
        false_target: 4,
    }));
    ssa.add_block(block1);

    // Block 2: loop body - sum += i; check break
    let mut block2 = SsaBlock::new(2);
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: sum_next_id,
        left: sum_phi_id,
        right: i_phi_id,
        flags: None,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: hundred_id,
        value: ConstValue::I32(100),
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Cgt {
        dest: break_cond_id,
        left: sum_next_id,
        right: hundred_id,
        unsigned: false,
    }));
    block2.add_instruction(SsaInstruction::synthetic(SsaOp::Branch {
        condition: break_cond_id,
        true_target: 4, // break
        false_target: 3,
    }));
    ssa.add_block(block2);

    // Block 3: continue - i++
    let mut block3 = SsaBlock::new(3);
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Const {
        dest: one_id,
        value: ConstValue::I32(1),
    }));
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Add {
        dest: i_next_id,
        left: i_phi_id,
        right: one_id,
        flags: None,
    }));
    block3.add_instruction(SsaInstruction::synthetic(SsaOp::Jump { target: 1 }));
    ssa.add_block(block3);

    // Block 4: exit (merge point for normal exit and break)
    // Note: in real SSA, we'd have another phi here for sum, but we simplify
    let mut block4 = SsaBlock::new(4);
    block4.add_instruction(SsaInstruction::synthetic(SsaOp::Return {
        value: Some(sum_phi_id),
    }));
    ssa.add_block(block4);

    // Generate and verify
    let mut gen = SsaCodeGenerator::new();
    let result = gen.generate(&ssa);
    assert!(result.is_ok(), "Codegen failed: {:?}", result.err());

    let (bytecode, _, _) = result.unwrap();
    let instructions = decode_stream(&mut Parser::new(&bytecode), 0x1000).expect("decode");
    let mnemonics: Vec<&str> = instructions.iter().map(|i| i.mnemonic).collect();

    // Should have two comparison types (clt for loop, cgt for break)
    assert!(
        mnemonics.contains(&"clt"),
        "Should have clt for loop condition"
    );
    assert!(
        mnemonics.contains(&"cgt"),
        "Should have cgt for break condition"
    );

    // Should have multiple branch points
    let branch_count = mnemonics.iter().filter(|m| m.starts_with("br")).count();
    assert!(
        branch_count >= 2,
        "Should have multiple branches for loop and break"
    );
}

/// A value on the CIL evaluation stack, as far as the integer tests need one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum StackValue {
    I4(i32),
    I8(i64),
}

/// The index a short-form or indexed load or store names.
fn indexed_operand(instr: &Instruction) -> usize {
    if let Some(digit) = instr
        .mnemonic
        .rsplit('.')
        .next()
        .and_then(|s| s.parse().ok())
    {
        return digit;
    }
    match &instr.operand {
        Operand::Local(index) | Operand::Argument(index) => usize::from(*index),
        Operand::Immediate(Immediate::UInt8(index)) => usize::from(*index),
        Operand::Immediate(Immediate::UInt16(index)) => usize::from(*index),
        other => panic!("{} has no index operand: {other:?}", instr.mnemonic),
    }
}

/// Runs straight-line integer CIL - the code a lowering emits - and returns
/// what it leaves for `ret`.
///
/// Knows only the instructions integer lowerings produce, and panics on
/// anything else, so a test never passes by skipping an instruction.
fn run_integer_cil(bytecode: &[u8], args: &[StackValue]) -> StackValue {
    run_integer_cil_with_handlers(bytecode, &[], args)
}

/// [`run_integer_cil`] over a body with exception clauses: a `leave` out of a
/// protected region runs the region's `finally` first, and `endfinally`
/// resumes at the leave's target. Nothing throws, so no other clause runs.
fn run_integer_cil_with_handlers(
    bytecode: &[u8],
    handlers: &[ExceptionHandler],
    args: &[StackValue],
) -> StackValue {
    let instructions = decode_stream(&mut Parser::new(bytecode), 0).expect("decode failed");
    let mut resume_at: Vec<u64> = Vec::new();
    let index_of = |offset: u64| {
        instructions
            .iter()
            .position(|i| i.offset == offset)
            .unwrap_or_else(|| panic!("branch into the middle of an instruction at {offset}"))
    };
    let mut stack: Vec<StackValue> = Vec::new();
    let mut locals: Vec<Option<StackValue>> = vec![None; 256];
    let mut args: Vec<StackValue> = args.to_vec();
    let pop = |stack: &mut Vec<StackValue>| stack.pop().expect("stack underflow");
    let mut pc = 0usize;
    let mut steps = 0usize;
    while let Some(instr) = instructions.get(pc) {
        steps += 1;
        assert!(steps < 100_000, "run_integer_cil did not terminate");
        pc += 1;
        let m = instr.mnemonic;
        let target = || match instr.branch_targets.first() {
            Some(&target) => index_of(target),
            None => panic!("{m} has no target"),
        };
        match m {
            "br" | "br.s" => pc = target(),
            "leave" | "leave.s" => {
                stack.clear();
                let destination = *instr.branch_targets.first().expect("leave has a target");
                let finally = handlers.iter().find(|clause| {
                    let start = u64::from(clause.try_offset);
                    let end = start + u64::from(clause.try_length);
                    clause.flags.contains(ExceptionHandlerFlags::FINALLY)
                        && (start..end).contains(&instr.offset)
                        && !(start..end).contains(&destination)
                });
                match finally {
                    Some(clause) => {
                        resume_at.push(destination);
                        pc = index_of(u64::from(clause.handler_offset));
                    }
                    None => pc = index_of(destination),
                }
            }
            "endfinally" => {
                pc = index_of(resume_at.pop().expect("endfinally outside a leave"));
            }
            "brtrue" | "brtrue.s" | "brfalse" | "brfalse.s" => {
                let truthy = match pop(&mut stack) {
                    StackValue::I4(v) => v != 0,
                    StackValue::I8(v) => v != 0,
                };
                if truthy == m.starts_with("brtrue") {
                    pc = target();
                }
            }
            "ceq" | "cgt" | "clt" | "beq" | "beq.s" | "bgt" | "bgt.s" | "blt" | "blt.s" | "bge"
            | "bge.s" | "ble" | "ble.s" | "bne.un" | "bne.un.s" => {
                let (b, a) = (pop(&mut stack), pop(&mut stack));
                let (a, b) = match (a, b) {
                    (StackValue::I4(a), StackValue::I4(b)) => (i64::from(a), i64::from(b)),
                    (StackValue::I8(a), StackValue::I8(b)) => (a, b),
                    _ => panic!("{m} over mixed widths"),
                };
                let holds = match m.trim_end_matches(".s") {
                    "ceq" | "beq" => a == b,
                    "cgt" | "bgt" => a > b,
                    "clt" | "blt" => a < b,
                    "bge" => a >= b,
                    "ble" => a <= b,
                    _ => a != b,
                };
                if m.starts_with('c') {
                    stack.push(StackValue::I4(i32::from(holds)));
                } else if holds {
                    pc = target();
                }
            }
            _ if m.starts_with("ldarg") => stack.push(args[indexed_operand(instr)]),
            _ if m.starts_with("starg") => {
                let value = pop(&mut stack);
                args[indexed_operand(instr)] = value;
            }
            _ if m.starts_with("ldloc") => {
                stack.push(locals[indexed_operand(instr)].expect("local read before written"));
            }
            _ if m.starts_with("stloc") => {
                let value = pop(&mut stack);
                locals[indexed_operand(instr)] = Some(value);
            }
            "ldc.i4.m1" => stack.push(StackValue::I4(-1)),
            _ if m.starts_with("ldc.i4.") && m.len() == 8 && m != "ldc.i4.s" => {
                let digit = m.strip_prefix("ldc.i4.").expect("ldc.i4.N");
                stack.push(StackValue::I4(digit.parse().expect("ldc.i4.N")));
            }
            "ldc.i4.s" | "ldc.i4" | "ldc.i8" => {
                let value = match &instr.operand {
                    Operand::Immediate(Immediate::Int8(v)) => StackValue::I4(i32::from(*v)),
                    Operand::Immediate(Immediate::Int32(v)) => StackValue::I4(*v),
                    Operand::Immediate(Immediate::Int64(v)) => StackValue::I8(*v),
                    other => panic!("{m} operand {other:?}"),
                };
                stack.push(value);
            }
            "dup" => {
                let top = *stack.last().expect("dup on empty stack");
                stack.push(top);
            }
            "pop" => {
                pop(&mut stack);
            }
            "and" | "or" | "xor" | "add" | "sub" | "mul" => {
                let (b, a) = (pop(&mut stack), pop(&mut stack));
                let result = match (a, b) {
                    (StackValue::I4(a), StackValue::I4(b)) => StackValue::I4(match m {
                        "and" => a & b,
                        "or" => a | b,
                        "xor" => a ^ b,
                        "add" => a.wrapping_add(b),
                        "sub" => a.wrapping_sub(b),
                        _ => a.wrapping_mul(b),
                    }),
                    (StackValue::I8(a), StackValue::I8(b)) => StackValue::I8(match m {
                        "and" => a & b,
                        "or" => a | b,
                        "xor" => a ^ b,
                        "add" => a.wrapping_add(b),
                        "sub" => a.wrapping_sub(b),
                        _ => a.wrapping_mul(b),
                    }),
                    _ => panic!("{m} over mixed widths {a:?}, {b:?}"),
                };
                stack.push(result);
            }
            "shl" | "shr" | "shr.un" => {
                let StackValue::I4(amount) = pop(&mut stack) else {
                    panic!("{m} amount is not int32");
                };
                let amount = u32::try_from(amount).expect("negative shift count");
                let result = match pop(&mut stack) {
                    StackValue::I4(v) => {
                        assert!(amount < 32, "{m} by {amount} is unspecified in CIL");
                        StackValue::I4(match m {
                            "shl" => v << amount,
                            "shr" => v >> amount,
                            _ => ((v as u32) >> amount) as i32,
                        })
                    }
                    StackValue::I8(v) => {
                        assert!(amount < 64, "{m} by {amount} is unspecified in CIL");
                        StackValue::I8(match m {
                            "shl" => v << amount,
                            "shr" => v >> amount,
                            _ => ((v as u64) >> amount) as i64,
                        })
                    }
                };
                stack.push(result);
            }
            "neg" => {
                let result = match pop(&mut stack) {
                    StackValue::I4(v) => StackValue::I4(v.wrapping_neg()),
                    StackValue::I8(v) => StackValue::I8(v.wrapping_neg()),
                };
                stack.push(result);
            }
            _ if m.starts_with("conv.") => {
                let bits = match pop(&mut stack) {
                    StackValue::I4(v) => i64::from(v),
                    StackValue::I8(v) => v,
                };
                let result = match m {
                    "conv.i1" => StackValue::I4(i32::from(bits as i8)),
                    "conv.u1" => StackValue::I4(i32::from(bits as u8)),
                    "conv.i2" => StackValue::I4(i32::from(bits as i16)),
                    "conv.u2" => StackValue::I4(i32::from(bits as u16)),
                    "conv.i4" | "conv.u4" => StackValue::I4(bits as i32),
                    "conv.i8" => StackValue::I8(bits),
                    other => panic!("unsupported {other}"),
                };
                stack.push(result);
            }
            "ret" => return pop(&mut stack),
            "nop" => {}
            other => panic!("run_integer_cil does not model {other}"),
        }
    }
    panic!("no ret");
}

/// A one-block function returning `op` applied to typed arguments, with the
/// result typed `result_type`.
fn single_op_function(
    arg_types: &[SsaType],
    result_type: SsaType,
    make_op: impl FnOnce(SsaVarId, &[SsaVarId]) -> SsaOp,
) -> SsaFunction {
    let mut result = None;
    let mut ssa = SsaFunctionBuilder::new(arg_types.len(), 0)
        .build_with(|f| {
            let args: Vec<SsaVarId> = arg_types
                .iter()
                .enumerate()
                .map(|(index, ty)| f.arg(index, ty.clone()))
                .collect();
            let dest = f.var();
            result = Some(dest);
            f.block(0, |b| {
                b.op(make_op(dest, &args));
                b.ret_val(dest);
            });
        })
        .unwrap();
    let dest = result.unwrap();
    ssa.variable_mut(dest).unwrap().set_type(result_type);
    ssa
}

